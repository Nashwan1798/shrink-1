export const THREE_PROJECTION = [
  "const { sin, cos, random } = Math;",
  "",
  "// 500 random points inside a cube from -1 to 1.",
  "const points = Array.from({ length: 500 }, () => [random() * 2 - 1, random() * 2 - 1, random() * 2 - 1]);",
  "",
  "function project([x, y, z], angle) {",
  "  // Spin around the vertical axis.",
  "  const rx = x * cos(angle) - z * sin(angle);",
  "  const rz = x * sin(angle) + z * cos(angle) + 3; // + 3 moves it away from the camera",
  "  const scale = c.height / rz;",
  "  return [c.width / 2 + rx * scale, c.height / 2 + y * scale, rz];",
  "}",
  "",
  "function draw(t) {",
  "  ctx.fillStyle = \"#000\";",
  "  ctx.fillRect(0, 0, c.width, c.height);",
  "  const projected = points.map((p) => project(p, t / 2000));",
  "  // Far things first, so near things draw on top.",
  "  projected.sort((a, b) => b[2] - a[2]);",
  "  for (const [x, y, z] of projected) {",
  "    const size = 12 / z;",
  "    ctx.fillStyle = `hsl(40 100% ${90 - z * 15}%)`;",
  "    ctx.fillRect(x - size / 2, y - size / 2, size, size);",
  "  }",
  "}",
].join("\n");
