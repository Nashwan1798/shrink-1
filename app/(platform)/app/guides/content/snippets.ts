export const WEBGL = [
  "<body>",
  "  <canvas id=\"c\"></canvas>",
  "  <style>",
  "    /* full screen */",
  "    body { margin: 0; background: #000; overflow: hidden; }",
  "    canvas { display: block; }",
  "  </style>",
  "  <script>",
  "    const glsl = (s) => s[0];",
  "    const gl = c.getContext(\"webgl\");",
  "",
  "    const vertex = glsl`",
  "      attribute vec2 p;",
  "      void main() { gl_Position = vec4(p, 0, 1); }",
  "    `;",
  "",
  "    const fragment = glsl`",
  "      precision mediump float;",
  "      uniform float t;",
  "      uniform vec2 r;",
  "",
  "      float scene(vec3 p) {",
  "        p.xz *= mat2(cos(t), -sin(t), sin(t), cos(t));",
  "        p.yz *= mat2(cos(t * .7), -sin(t * .7), sin(t * .7), cos(t * .7));",
  "        return length(max(abs(p) - .6, 0.)) - .1;",
  "      }",
  "",
  "      void main() {",
  "        vec2 uv = (gl_FragCoord.xy * 2. - r) / r.y;",
  "        vec3 p = vec3(0, 0, -3), dir = normalize(vec3(uv, 1.5));",
  "        float d = 1.;",
  "        for (int i = 0; i < 80; i++) {",
  "          d = scene(p);",
  "          if (d < .001) break;",
  "          p += dir * d;",
  "        }",
  "        vec3 color = vec3(0);",
  "        if (d < .001) {",
  "          vec2 e = vec2(.001, 0);",
  "          vec3 n = normalize(vec3(",
  "            scene(p + e.xyy) - scene(p - e.xyy),",
  "            scene(p + e.yxy) - scene(p - e.yxy),",
  "            scene(p + e.yyx) - scene(p - e.yyx)",
  "          ));",
  "          color = vec3(1, .75, .1) * max(dot(n, normalize(vec3(1, 1, -1))), .15);",
  "        }",
  "        gl_FragColor = vec4(color, 1);",
  "      }",
  "    `;",
  "",
  "    const program = gl.createProgram();",
  "    for (const [type, source] of [[gl.VERTEX_SHADER, vertex], [gl.FRAGMENT_SHADER, fragment]]) {",
  "      const shader = gl.createShader(type);",
  "      gl.shaderSource(shader, source);",
  "      gl.compileShader(shader);",
  "      gl.attachShader(program, shader);",
  "    }",
  "    gl.linkProgram(program);",
  "    gl.useProgram(program);",
  "",
  "    // One triangle big enough to cover the whole screen.",
  "    gl.bindBuffer(gl.ARRAY_BUFFER, gl.createBuffer());",
  "    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);",
  "    gl.enableVertexAttribArray(0);",
  "    gl.vertexAttribPointer(0, 2, gl.FLOAT, false, 0, 0);",
  "",
  "    const time = gl.getUniformLocation(program, \"t\");",
  "    const size = gl.getUniformLocation(program, \"r\");",
  "",
  "    onresize = () => {",
  "      c.width = innerWidth;",
  "      c.height = innerHeight;",
  "      gl.viewport(0, 0, c.width, c.height);",
  "      gl.uniform2f(size, c.width, c.height);",
  "    };",
  "    onresize();",
  "",
  "    function frame(ms) {",
  "      gl.uniform1f(time, ms / 1000);",
  "      gl.drawArrays(gl.TRIANGLES, 0, 3);",
  "      requestAnimationFrame(frame);",
  "    }",
  "    requestAnimationFrame(frame);",
  "  </script>",
  "</body>",
].join("\n");

export const SOUND_BEEP = [
  "let audio;",
  "onpointerdown = () => (audio ??= new AudioContext());",
  "",
  "function beep(freq, length = 0.2, type = \"square\", when = audio.currentTime) {",
  "  const osc = audio.createOscillator();",
  "  const gain = audio.createGain();",
  "  osc.type = type;",
  "  osc.frequency.value = freq;",
  "  // Start loud, fade out. Ramping to 0.001 instead of 0 because",
  "  // exponential ramps can't reach zero.",
  "  gain.gain.setValueAtTime(0.2, when);",
  "  gain.gain.exponentialRampToValueAtTime(0.001, when + length);",
  "  osc.connect(gain).connect(audio.destination);",
  "  osc.start(when);",
  "  osc.stop(when + length);",
  "}",
].join("\n");

